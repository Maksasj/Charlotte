def load(name):
    p = os.path.join(D, name + ".json")
    return json.load(open(p)) if os.path.exists(p) else None


def wilson(k, n, z=1.959964):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return (max(0.0, c - h), min(1.0, c + h))


def pct(k, n):
    return f"{100 * k / n:.1f}%" if n else "-"


def by_id(run):
    return {s["id"]: s for s in run["scored"]}


def questions():
    return {json.loads(l)["id"]: json.loads(l) for l in open(os.path.join(ROOT, "data/spike4/bench/questions.jsonl"))}


def legacy_class(s, q):
    """The class under the first scorer (before the two format fixes): raw string match."""
    norm = lambda a: a.replace(" ", "").rstrip(".")
    gold = [norm(a) for a in q["gold"]["atoms"]]
    claims = s["claims"]
    if q["gold"]["kind"] == "gap":
        return "correct" if not claims else "wrong"
    if gold and all(g in claims for g in gold):
        return "correct"
    return "gap" if not claims else "wrong"


