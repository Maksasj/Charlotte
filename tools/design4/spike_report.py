def count_status(run):
    c = {}
    for r in run["learned_rules"]:
        c[r["status"]] = c.get(r["status"], 0) + 1
    return c


def learned_add(full, nl):
    if not nl:
        return {"plus": 0, "wrong_added": 0}
    a, b = by_id(full), by_id(nl)
    plus = sum(1 for i in a if a[i]["class"] == "correct" and b[i]["class"] != "correct")
    minus = sum(1 for i in a if a[i]["class"] != "correct" and b[i]["class"] == "correct")
    wrong_added = sum(1 for i in a if a[i]["class"] in ("wrong", "invented") and b[i]["class"] not in ("wrong", "invented"))
    return {"plus": plus - minus, "wrong_added": wrong_added}


def check_proofs():
    p = os.path.join(D, "full_proofs.jsonl")
    r = subprocess.run(["python3", "-I", os.path.join(ROOT, "tools/design4/ref_reason.py"), "--proofs", p, "--facts", p + ".facts"], capture_output=True, text=True)
    return json.loads(r.stdout.strip().splitlines()[-1])


